uint8_t bsp_utils_calc_crc8(const uint8_t *data, uint16_t len) {
    uint8_t crc = 0x00; // 初始值
    if (data == NULL) return 0;
    
    while (len--) {
        // 利用异或结果直接从表中获取下一个状态，效率极高
        crc = crc8_table[crc ^ *data++];
    }
    return crc;
}

